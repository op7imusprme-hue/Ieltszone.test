const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ baseURL: 'https://demo-main.ieltszoneapp.uz', storageState: '.auth/ceo.json', viewport:{width:1440,height:900} });
  const p = await ctx.newPage();
  p.on('response', async r => { if (r.request().method()!=='GET') console.log('RESP', r.request().method(), new URL(r.url()).pathname, r.status(), (r.request().postData()||'').slice(0,400)); });
  await p.goto('/admin/placement-test/257'); await p.waitForLoadState('networkidle');
  await p.getByRole('button', { name: 'Add section' }).click(); await p.waitForTimeout(2500);
  console.log('---SHOW sections', await p.locator('main').innerText().then(t=>t.slice(t.indexOf('Sections'))));
  await p.getByRole('link', { name: 'Edit section questions' }).first().click(); await p.waitForURL(/edit$/); await p.waitForLoadState('networkidle');
  console.log('SECTION URL', p.url());
  console.log('---SECTION EDIT', await p.locator('main').innerText());
  await p.locator('#title').fill('');
  await p.getByRole('button', { name: 'Save section' }).click(); await p.waitForTimeout(2500);
  console.log('errs empty', await p.locator('p[id$="-error"], .text-red-600, .text-red-500').allInnerTexts());
  console.log('URL', p.url());
  // add MC question with no text
  await p.locator('#title').fill('S1');
  await p.getByRole('button', { name: 'Add Question', exact: true }).click(); await p.waitForTimeout(500);
  console.log('---AFTER ADD Q', await p.locator('main').innerText());
  const typeLabel = p.locator('label[for^="question_type_"]').last();
  const id = (await typeLabel.getAttribute('for')).replace('question_type_','');
  await p.locator(`xpath=//label[@for="question_type_${id}"]/../following-sibling::*[1]`).locator('.multiselect-wrapper').click();
  console.log('types', await p.locator('[role="option"]:visible').allInnerTexts());
  await p.locator('[role="option"]:visible').filter({hasText:/^Multiple Choice$/}).first().click();
  await p.waitForTimeout(500);
  console.log('---MC', await p.locator('main').innerText());
  await p.getByRole('button', { name: 'Save section' }).click(); await p.waitForTimeout(3000);
  console.log('errs mc empty', await p.locator('p[id$="-error"], .text-red-600, .text-red-500').allInnerTexts());
  console.log('toasts', await p.locator('[role="alert"], .toast, [class*="toast"]').allInnerTexts().catch(()=>[]));
  await p.screenshot({path:'explore/section.png', fullPage:true});
  await b.close();
})();
